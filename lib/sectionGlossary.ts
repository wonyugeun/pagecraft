export function sectionDescription(name: string): string | undefined {
  const n = String(name ?? '').trim();
  if (!n) return undefined;
  if (GLOSSARY[n]) return GLOSSARY[n];
  for (const [kw, desc] of KEYWORD_FALLBACK) {
    if (n.includes(kw)) return desc;
  }
  return undefined;
}
