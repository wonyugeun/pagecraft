/** 이 섹션이 재료를 요구하는가, 그리고 셀러가 이미 적었는가 */
export function materialNeedFor(sectionName: string, facts: string): MaterialNeed | null {
  const name = (sectionName ?? '').toLowerCase();
  const hay = (facts ?? '').toLowerCase();
  for (const m of MATERIAL_NEEDS) {
    if (!m.match.some(k => name.includes(k.toLowerCase()))) continue;
    if (m.probe.some(p => hay.includes(p.toLowerCase()))) return null;   // 이미 적었으면 조용히
    return m;
  }
  return null;
}
