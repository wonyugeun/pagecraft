/** 공백·기호를 지운 소문자 — '시카 토너'와 '시카토너'를 같게 본다 */
function normalize(s: string): string {
  return s.toLowerCase().replace(/[\s\-_·,./()[\]]/g, '');
}

/**
 * 상품명에서 카테고리를 추측한다. 확신이 없으면 null(= 셀러가 직접 고른다).
 *
 * 규칙 두 개뿐이다:
 *  1) 대상 낱말(강아지·아기·차량용)이 있으면 그 카테고리가 이긴다 — '강아지 사료'는 식품이 아니다.
 *  2) 그 외에는 걸린 낱말이 가장 긴 쪽. 긴 낱말일수록 우연히 겹칠 확률이 낮다
 *     ('클렌징오일'은 '오일'보다 확실하다).
 */
export function guessCategory(productName: string): string | null {
  const raw = (productName ?? '').trim();
  if (raw.length < 2) return null;
  const hay = normalize(raw);
  if (!hay) return null;

  for (const [cat, marks] of AUDIENCE) {
    if (marks.some(m => hay.includes(m))) return cat;
  }

  let best: string | null = null;
  let bestLen = 0;
  for (const [cat, words] of Object.entries(KEYWORDS)) {
    for (const w of words) {
      if (w.length > bestLen && hay.includes(w)) { bestLen = w.length; best = cat; }
    }
  }
  // 한 글자 차이로 갈리는 추측은 하지 않는다 — 두 글자 이상 걸렸을 때만 인정
  return bestLen >= 2 ? best : null;
}
